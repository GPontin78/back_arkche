/* MAURO web/app: histórico persistente por usuário e conta ativa. */
SET BAIL ON;

CREATE TABLE MAURO_CONVERSA (
    ID_CONVERSA BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ID_USUARIO INTEGER NOT NULL,
    ID_CONTA INTEGER NOT NULL,
    TITULO VARCHAR(120) DEFAULT 'Conversa com MAURO' NOT NULL,
    CRIADA_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADA_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_MAURO_CONVERSA PRIMARY KEY (ID_CONVERSA),
    CONSTRAINT FK_MAURO_CONV_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT FK_MAURO_CONV_CONTA FOREIGN KEY (ID_CONTA) REFERENCES CONTA (ID_CONTA)
);

CREATE INDEX IX_MAURO_CONV_USUARIO_CONTA
    ON MAURO_CONVERSA (ID_USUARIO, ID_CONTA, ATUALIZADA_EM);

CREATE TABLE MAURO_MENSAGEM (
    ID_MENSAGEM BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ID_CONVERSA BIGINT NOT NULL,
    PAPEL VARCHAR(12) NOT NULL,
    CONTEUDO VARCHAR(4000) NOT NULL,
    CRIADA_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_MAURO_MENSAGEM PRIMARY KEY (ID_MENSAGEM),
    CONSTRAINT FK_MAURO_MSG_CONVERSA FOREIGN KEY (ID_CONVERSA)
        REFERENCES MAURO_CONVERSA (ID_CONVERSA),
    CONSTRAINT CK_MAURO_MSG_PAPEL CHECK (PAPEL IN ('USUARIO', 'ASSISTENTE'))
);

CREATE INDEX IX_MAURO_MSG_CONVERSA_DATA
    ON MAURO_MENSAGEM (ID_CONVERSA, CRIADA_EM, ID_MENSAGEM);

COMMIT;
