/* Registros aditivos para cancelamento de cobrancas pendentes e devolucoes.
   As movimentacoes originais permanecem imutaveis; devolucoes sao novas linhas
   inversas em MOVIMENTACAO e apontam para sua origem nesta tabela. */

SET BAIL ON;

CREATE TABLE ESTORNO_FINANCEIRO (
    ID_ESTORNO INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    TIPO_OPERACAO VARCHAR(32) NOT NULL,
    ID_COBRANCA INTEGER,
    ID_MOVIMENTACAO_ORIGINAL INTEGER,
    ID_MOVIMENTACAO_REVERSA INTEGER,
    ID_CONTA_SOLICITANTE INTEGER NOT NULL,
    ID_USUARIO_RESPONSAVEL INTEGER NOT NULL,
    ID_CONTA_PAGADOR INTEGER,
    ID_CONTA_RECEBEDOR INTEGER NOT NULL,
    VALOR DECIMAL(18,2) NOT NULL,
    STATUS VARCHAR(16) NOT NULL,
    MOTIVO VARCHAR(500) NOT NULL,
    CHAVE_IDEMPOTENCIA VARCHAR(100) NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_ESTORNO_FIN PRIMARY KEY (ID_ESTORNO),
    CONSTRAINT UQ_ESTORNO_IDEMP UNIQUE (CHAVE_IDEMPOTENCIA),
    CONSTRAINT FK_ESTORNO_COB FOREIGN KEY (ID_COBRANCA) REFERENCES COBRANCA (ID_COBRANCA),
    CONSTRAINT FK_ESTORNO_MOV_ORIG FOREIGN KEY (ID_MOVIMENTACAO_ORIGINAL) REFERENCES MOVIMENTACAO (ID_MOVIMENTACAO),
    CONSTRAINT FK_ESTORNO_MOV_REV FOREIGN KEY (ID_MOVIMENTACAO_REVERSA) REFERENCES MOVIMENTACAO (ID_MOVIMENTACAO),
    CONSTRAINT FK_ESTORNO_CONTA_SOL FOREIGN KEY (ID_CONTA_SOLICITANTE) REFERENCES CONTA (ID_CONTA),
    CONSTRAINT FK_ESTORNO_USUARIO FOREIGN KEY (ID_USUARIO_RESPONSAVEL) REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT FK_ESTORNO_CONTA_PAG FOREIGN KEY (ID_CONTA_PAGADOR) REFERENCES CONTA (ID_CONTA),
    CONSTRAINT FK_ESTORNO_CONTA_REC FOREIGN KEY (ID_CONTA_RECEBEDOR) REFERENCES CONTA (ID_CONTA),
    CONSTRAINT CK_ESTORNO_TIPO CHECK (TIPO_OPERACAO IN ('CANCELAMENTO_COBRANCA', 'DEVOLUCAO_PIX_TRANSFERENCIA', 'ESTORNO_BOLETO')),
    CONSTRAINT CK_ESTORNO_STATUS CHECK (STATUS IN ('CANCELADO', 'CONCLUIDO', 'RECUSADO')),
    CONSTRAINT CK_ESTORNO_VALOR CHECK (VALOR >= 0),
    CONSTRAINT CK_ESTORNO_REFERENCIA CHECK (
        (TIPO_OPERACAO = 'CANCELAMENTO_COBRANCA' AND ID_COBRANCA IS NOT NULL AND ID_MOVIMENTACAO_ORIGINAL IS NULL AND ID_MOVIMENTACAO_REVERSA IS NULL)
        OR
        (TIPO_OPERACAO = 'ESTORNO_BOLETO' AND ID_COBRANCA IS NOT NULL AND ID_MOVIMENTACAO_ORIGINAL IS NOT NULL)
        OR
        (TIPO_OPERACAO = 'DEVOLUCAO_PIX_TRANSFERENCIA' AND ID_MOVIMENTACAO_ORIGINAL IS NOT NULL)
    ),
    CONSTRAINT CK_ESTORNO_RESULTADO CHECK (
        (STATUS = 'CONCLUIDO' AND ID_MOVIMENTACAO_REVERSA IS NOT NULL)
        OR
        (STATUS <> 'CONCLUIDO' AND ID_MOVIMENTACAO_REVERSA IS NULL)
    )
);

CREATE INDEX IX_ESTORNO_ORIGINAL ON ESTORNO_FINANCEIRO (ID_MOVIMENTACAO_ORIGINAL, STATUS);
CREATE INDEX IX_ESTORNO_CONTA_DATA ON ESTORNO_FINANCEIRO (ID_CONTA_SOLICITANTE, CRIADO_EM);
CREATE INDEX IX_ESTORNO_COBRANCA ON ESTORNO_FINANCEIRO (ID_COBRANCA, STATUS);

COMMIT;
