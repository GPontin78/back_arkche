-- Executar uma única vez no Firebird 4 do Arkhé, após realizar backup.
-- Não executa automaticamente na inicialização da API.
CREATE TABLE WHATSAPP_CONFIG (
    ID_USUARIO INTEGER NOT NULL,
    ID_CONTA INTEGER NOT NULL,
    TELEFONE VARCHAR(20) NOT NULL,
    NIVEL SMALLINT DEFAULT 0 NOT NULL,
    CODIGO_HASH VARCHAR(64),
    CODIGO_EXPIRA TIMESTAMP,
    TENTATIVAS SMALLINT DEFAULT 0 NOT NULL,
    CODIGO_GERADO_EM TIMESTAMP,
    CONSTRAINT PK_WHATSAPP_CONFIG PRIMARY KEY (ID_USUARIO, ID_CONTA),
    CONSTRAINT FK_WA_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT FK_WA_CONTA FOREIGN KEY (ID_CONTA) REFERENCES CONTA (ID_CONTA),
    CONSTRAINT CK_WA_NIVEL CHECK (NIVEL IN (0, 1))
);
CREATE INDEX IDX_WHATSAPP_TELEFONE ON WHATSAPP_CONFIG (TELEFONE);

CREATE TABLE WHATSAPP_SESSAO (
    ID_USUARIO INTEGER NOT NULL,
    ID_CONTA INTEGER NOT NULL,
    TELEFONE VARCHAR(20) NOT NULL,
    VALIDA_ATE TIMESTAMP NOT NULL,
    CONSTRAINT PK_WHATSAPP_SESSAO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT FK_WAS_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT FK_WAS_CONTA FOREIGN KEY (ID_CONTA) REFERENCES CONTA (ID_CONTA)
);
CREATE INDEX IDX_WHATSAPP_SESSAO_TELEFONE ON WHATSAPP_SESSAO (TELEFONE);
COMMIT;
