/* Regras recorrentes sao materializadas em agendamentos financeiros no momento
   devido. Cada parcela guarda uma ligacao unica ao agendamento existente. */

SET BAIL ON;

CREATE TABLE RECORRENCIA_FINANCEIRA (
    ID_RECORRENCIA INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ID_USUARIO INTEGER NOT NULL,
    ID_CONTA INTEGER NOT NULL,
    TIPO_OPERACAO VARCHAR(20) NOT NULL,
    ID_CONTA_DESTINO INTEGER,
    ID_COBRANCA INTEGER,
    TIPO_CHAVE VARCHAR(12),
    HASH_CHAVE CHAR(64),
    VALOR DECIMAL(18,2) NOT NULL,
    FREQUENCIA VARCHAR(12) NOT NULL,
    DATA_INICIAL TIMESTAMP NOT NULL,
    DATA_FINAL DATE,
    LIMITE_EXECUCOES INTEGER,
    EXECUCOES_CRIADAS INTEGER DEFAULT 0 NOT NULL,
    DIA_MES SMALLINT,
    PROXIMA_EXECUCAO TIMESTAMP,
    STATUS VARCHAR(12) DEFAULT 'ATIVA' NOT NULL,
    AUTORIZADA_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CANCELADO_EM TIMESTAMP,
    CONSTRAINT PK_REC_FIN PRIMARY KEY (ID_RECORRENCIA),
    CONSTRAINT FK_REC_FIN_USER FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT FK_REC_FIN_CONTA FOREIGN KEY (ID_CONTA) REFERENCES CONTA (ID_CONTA),
    CONSTRAINT FK_REC_FIN_DEST FOREIGN KEY (ID_CONTA_DESTINO) REFERENCES CONTA (ID_CONTA),
    CONSTRAINT FK_REC_FIN_COB FOREIGN KEY (ID_COBRANCA) REFERENCES COBRANCA (ID_COBRANCA),
    CONSTRAINT CK_REC_FIN_TIPO CHECK (TIPO_OPERACAO IN ('TRANSFERENCIA', 'PIX_COBRANCA', 'BOLETO')),
    CONSTRAINT CK_REC_FIN_FREQ CHECK (FREQUENCIA IN ('SEMANAL', 'QUINZENAL', 'MENSAL')),
    CONSTRAINT CK_REC_FIN_STATUS CHECK (STATUS IN ('ATIVA', 'PAUSADA', 'CANCELADA', 'FINALIZADA')),
    CONSTRAINT CK_REC_FIN_VALOR CHECK (VALOR > 0),
    CONSTRAINT CK_REC_FIN_MAX CHECK (LIMITE_EXECUCOES IS NULL OR LIMITE_EXECUCOES BETWEEN 1 AND 1200),
    CONSTRAINT CK_REC_FIN_FIM CHECK (DATA_FINAL IS NULL OR LIMITE_EXECUCOES IS NULL),
    CONSTRAINT CK_REC_FIN_DIA CHECK (DIA_MES IS NULL OR DIA_MES BETWEEN 1 AND 31),
    CONSTRAINT CK_REC_FIN_ALVO CHECK (
        (TIPO_OPERACAO = 'TRANSFERENCIA' AND ID_CONTA_DESTINO IS NOT NULL AND ID_COBRANCA IS NULL AND TIPO_CHAVE IS NOT NULL AND HASH_CHAVE IS NOT NULL)
        OR
        (TIPO_OPERACAO IN ('PIX_COBRANCA', 'BOLETO') AND ID_CONTA_DESTINO IS NULL AND ID_COBRANCA IS NOT NULL AND TIPO_CHAVE IS NULL AND HASH_CHAVE IS NULL)
    )
);

CREATE INDEX IX_REC_FIN_PENDENTE
    ON RECORRENCIA_FINANCEIRA (STATUS, PROXIMA_EXECUCAO);
CREATE INDEX IX_REC_FIN_USUARIO_CONTA
    ON RECORRENCIA_FINANCEIRA (ID_USUARIO, ID_CONTA, CRIADO_EM);

CREATE TABLE RECORRENCIA_EXECUCAO (
    ID_REC_EXECUCAO INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ID_RECORRENCIA INTEGER NOT NULL,
    NUMERO_EXECUCAO INTEGER NOT NULL,
    ID_AGENDAMENTO INTEGER NOT NULL,
    DATA_PREVISTA TIMESTAMP NOT NULL,
    STATUS VARCHAR(12) DEFAULT 'AGENDADO' NOT NULL,
    MOTIVO_FALHA VARCHAR(500),
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_REC_EXEC PRIMARY KEY (ID_REC_EXECUCAO),
    CONSTRAINT UQ_REC_EXEC_NUM UNIQUE (ID_RECORRENCIA, NUMERO_EXECUCAO),
    CONSTRAINT UQ_REC_EXEC_AGEND UNIQUE (ID_AGENDAMENTO),
    CONSTRAINT FK_REC_EXEC_REC FOREIGN KEY (ID_RECORRENCIA) REFERENCES RECORRENCIA_FINANCEIRA (ID_RECORRENCIA),
    CONSTRAINT FK_REC_EXEC_AGEND FOREIGN KEY (ID_AGENDAMENTO) REFERENCES AGENDAMENTO_FINANCEIRO (ID_AGENDAMENTO),
    CONSTRAINT CK_REC_EXEC_STATUS CHECK (STATUS IN ('AGENDADO', 'EXECUTANDO', 'CONCLUIDO', 'FALHOU', 'CANCELADO')),
    CONSTRAINT CK_REC_EXEC_NUM CHECK (NUMERO_EXECUCAO > 0)
);

CREATE INDEX IX_REC_EXEC_REC_DATA
    ON RECORRENCIA_EXECUCAO (ID_RECORRENCIA, DATA_PREVISTA);

COMMIT;
