/*
  Auditoria transacional (banco principal). Aplicar uma vez, apos backup.
  Os triggers apenas escrevem no outbox da mesma transacao. O worker so envia
  eventos que ficaram visiveis depois do COMMIT original.
  Nao registrar PIN, senhas, CVV, tokens ou codigos de pagamento.
*/

SET BAIL ON;

CREATE TABLE AUDITORIA_EVENTO_OUTBOX (
    ID_EVENTO BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    EVENTO VARCHAR(48) NOT NULL,
    TABELA_ORIGEM VARCHAR(64) NOT NULL,
    OPERACAO VARCHAR(12) NOT NULL,
    ID_REGISTRO BIGINT,
    ID_USUARIO INTEGER,
    ID_CONTA INTEGER,
    VALOR DECIMAL(18,2),
    RESULTADO VARCHAR(24) NOT NULL,
    MOTIVO VARCHAR(500),
    ORIGEM VARCHAR(160),
    DADOS_ANTERIORES VARCHAR(4000),
    DADOS_NOVOS VARCHAR(4000),
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    AUDITADO_EM TIMESTAMP,
    PUBLICADO_EM TIMESTAMP,
    TENTATIVAS INTEGER DEFAULT 0 NOT NULL,
    PROXIMA_TENTATIVA TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    BLOQUEIO_TOKEN VARCHAR(36),
    BLOQUEIO_ATE TIMESTAMP,
    ERRO_ULTIMO VARCHAR(500),
    CONSTRAINT PK_AUD_EVENTO_OUTBOX PRIMARY KEY (ID_EVENTO),
    CONSTRAINT CK_AUD_EVENTO_OPER CHECK (OPERACAO IN ('INSERT', 'UPDATE', 'DELETE', 'READ', 'DENY'))
);

CREATE INDEX IX_AUD_EVENTO_PENDENTE
    ON AUDITORIA_EVENTO_OUTBOX (AUDITADO_EM, PUBLICADO_EM, PROXIMA_TENTATIVA, BLOQUEIO_ATE);
CREATE INDEX IX_AUD_EVENTO_CONTA_DATA
    ON AUDITORIA_EVENTO_OUTBOX (ID_CONTA, CRIADO_EM);
CREATE INDEX IX_AUD_EVENTO_USUARIO_DATA
    ON AUDITORIA_EVENTO_OUTBOX (ID_USUARIO, CRIADO_EM);

SET TERM ^;

CREATE OR ALTER PROCEDURE ARKHE_AUDIT_ENQUEUE (
    P_EVENTO VARCHAR(48), P_TABELA VARCHAR(64), P_OPERACAO VARCHAR(12),
    P_ID_REGISTRO BIGINT, P_ID_USUARIO INTEGER, P_ID_CONTA INTEGER,
    P_VALOR DECIMAL(18,2), P_RESULTADO VARCHAR(24), P_MOTIVO VARCHAR(500),
    P_ORIGEM VARCHAR(160), P_ANTERIOR VARCHAR(4000), P_NOVO VARCHAR(4000)
) AS
BEGIN
    INSERT INTO AUDITORIA_EVENTO_OUTBOX
      (EVENTO, TABELA_ORIGEM, OPERACAO, ID_REGISTRO, ID_USUARIO, ID_CONTA,
       VALOR, RESULTADO, MOTIVO, ORIGEM, DADOS_ANTERIORES, DADOS_NOVOS)
    VALUES
      (:P_EVENTO, :P_TABELA, :P_OPERACAO, :P_ID_REGISTRO, :P_ID_USUARIO,
       :P_ID_CONTA, :P_VALOR, :P_RESULTADO, :P_MOTIVO, :P_ORIGEM,
       :P_ANTERIOR, :P_NOVO);
END^

/* A tabela existente ja e o registro Python canonico de limites; estes
   triggers apenas copiam o registro comprometido para o outbox distribuido. */
CREATE TRIGGER ARKHE_AUD_LIMITE_AI FOR AUDITORIA_LIMITE ACTIVE AFTER INSERT POSITION 32000 AS
DECLARE VARIABLE V_NOVO VARCHAR(4000);
DECLARE VARIABLE V_EVENTO VARCHAR(48);
DECLARE VARIABLE V_RESULTADO VARCHAR(24);
DECLARE VARIABLE V_OPERACAO VARCHAR(12);
DECLARE VARIABLE V_MOTIVO VARCHAR(500);
BEGIN
  V_EVENTO = CASE NEW.EVENTO WHEN 'OPERACAO_RECUSADA' THEN 'OPERACAO_RECUSADA_LIMITE' ELSE 'LIMITE_POLITICA_ALTERADA' END;
  V_RESULTADO = CASE NEW.EVENTO WHEN 'OPERACAO_RECUSADA' THEN 'RECUSADO' ELSE 'SUCESSO' END;
  V_OPERACAO = CASE NEW.EVENTO WHEN 'OPERACAO_RECUSADA' THEN 'DENY' ELSE 'UPDATE' END;
  V_MOTIVO = CASE NEW.EVENTO WHEN 'OPERACAO_RECUSADA' THEN 'Operação recusada por limite' ELSE 'Política de limite alterada' END;
  V_NOVO = '{"id_auditoria_limite":' || CAST(NEW.ID_AUDITORIA AS VARCHAR(20)) ||
    ',"evento":"' || NEW.EVENTO || '","id_administrador":' || COALESCE(CAST(NEW.ID_ADMINISTRADOR AS VARCHAR(20)), 'null') ||
    ',"id_usuario":' || COALESCE(CAST(NEW.ID_USUARIO AS VARCHAR(20)), 'null') ||
    ',"id_conta":' || COALESCE(CAST(NEW.ID_CONTA AS VARCHAR(20)), 'null') ||
    ',"tipo_conta":"' || COALESCE(NEW.TIPO_CONTA, '') || '","operacao":"' || COALESCE(NEW.OPERACAO, '') ||
    '","periodo":"' || COALESCE(NEW.PERIODO, '') || '","valor_solicitado":' ||
    COALESCE(CAST(NEW.VALOR_SOLICITADO AS VARCHAR(32)), 'null') ||
    ',"valor_acumulado":' || COALESCE(CAST(NEW.VALOR_ACUMULADO AS VARCHAR(32)), 'null') ||
    ',"detalhes":' || COALESCE(NEW.DETALHES_JSON, 'null') || '}';
  EXECUTE PROCEDURE ARKHE_AUDIT_ENQUEUE(:V_EVENTO, 'AUDITORIA_LIMITE', :V_OPERACAO,
    NEW.ID_AUDITORIA, COALESCE(NEW.ID_USUARIO, NEW.ID_ADMINISTRADOR), NEW.ID_CONTA,
    NEW.VALOR_SOLICITADO, :V_RESULTADO, :V_MOTIVO,
    RDB$GET_CONTEXT('USER_SESSION', 'ARKHE_ORIGEM'), NULL, :V_NOVO);
END^

