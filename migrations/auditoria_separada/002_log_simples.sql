/* Executar no banco separado de LOG. O histórico AUDITORIA_EVENTO permanece. */
SET BAIL ON;
SET AUTODDL OFF;
CREATE TABLE LOG (
    ID_LOG BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    DATA_HORA TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    USUARIO VARCHAR(100),
    TABELA VARCHAR(64) NOT NULL,
    ID_REGISTRO BIGINT,
    ACAO VARCHAR(120) NOT NULL,
    VALOR_ANTERIOR BLOB SUB_TYPE TEXT,
    VALOR_NOVO BLOB SUB_TYPE TEXT
);
CREATE INDEX IX_LOG_DATA ON LOG (DATA_HORA);
CREATE INDEX IX_LOG_USUARIO ON LOG (USUARIO, DATA_HORA);
COMMIT;
