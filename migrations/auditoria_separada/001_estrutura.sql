/*
  Executar no banco Firebird SEPARADO da auditoria, nunca no banco principal.
  Aplicacao aditiva; a chave de origem torna a persistencia idempotente.
*/
SET BAIL ON;

CREATE TABLE AUDITORIA_EVENTO (
    ID_AUDITORIA BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ORIGEM_ID VARCHAR(80) NOT NULL,
    ID_EVENTO_ORIGEM BIGINT NOT NULL,
    EVENTO VARCHAR(48) NOT NULL,
    TABELA_ORIGEM VARCHAR(64) NOT NULL,
    OPERACAO VARCHAR(12) NOT NULL,
    ID_REGISTRO BIGINT,
    ID_USUARIO INTEGER,
    ID_CONTA INTEGER,
    VALOR DECIMAL(18,2),
    RESULTADO VARCHAR(24) NOT NULL,
    MOTIVO VARCHAR(500),
    ORIGEM VARCHAR(160),
    DADOS_ANTERIORES VARCHAR(4000),
    DADOS_NOVOS VARCHAR(4000),
    CRIADO_EM TIMESTAMP NOT NULL,
    RECEBIDO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_AUDITORIA_EVENTO PRIMARY KEY (ID_AUDITORIA),
    CONSTRAINT UQ_AUD_EVENTO_ORIGEM UNIQUE (ORIGEM_ID, ID_EVENTO_ORIGEM)
);

CREATE INDEX IX_AUDITORIA_EVENTO_DATA ON AUDITORIA_EVENTO (CRIADO_EM);
CREATE INDEX IX_AUDITORIA_EVENTO_USUARIO ON AUDITORIA_EVENTO (ID_USUARIO, CRIADO_EM);
CREATE INDEX IX_AUDITORIA_EVENTO_CONTA ON AUDITORIA_EVENTO (ID_CONTA, CRIADO_EM);
CREATE INDEX IX_AUDITORIA_EVENTO_TIPO ON AUDITORIA_EVENTO (EVENTO, CRIADO_EM);
COMMIT;
