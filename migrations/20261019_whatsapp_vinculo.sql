-- Etapa 1: vinculacao autorizada por conversa WhatsApp (Firebird 4).
-- Aplicar somente apos backup e verificacao do esquema em producao.
-- Requer as tabelas WHATSAPP_CONFIG e WHATSAPP_SESSAO da migracao anterior.
CREATE TABLE WHATSAPP_VINCULO_PENDENTE (
    TOKEN_HASH CHAR(64) NOT NULL PRIMARY KEY,
    ID_USUARIO INTEGER NOT NULL,
    ID_CONTA INTEGER NOT NULL,
    EXPIRA_EM TIMESTAMP NOT NULL,
    CRIADO_EM TIMESTAMP NOT NULL,
    CONSTRAINT FK_WVP_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT FK_WVP_CONTA FOREIGN KEY (ID_CONTA) REFERENCES CONTA (ID_CONTA)
);
CREATE INDEX IDX_WVP_USUARIO_CONTA ON WHATSAPP_VINCULO_PENDENTE (ID_USUARIO, ID_CONTA);

CREATE TABLE WHATSAPP_IDENTIDADE (
    CHAT_ID VARCHAR(64) NOT NULL PRIMARY KEY,
    ID_USUARIO INTEGER NOT NULL,
    VINCULADO_EM TIMESTAMP NOT NULL,
    CONSTRAINT FK_WI_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO)
);
CREATE INDEX IDX_WI_USUARIO ON WHATSAPP_IDENTIDADE (ID_USUARIO);
COMMIT;
