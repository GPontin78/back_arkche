/*
   Etapa 1A — notificacoes e outbox persistente.
   Aplicar uma unica vez no Firebird local/de implantacao depois de backup.
   Nao altera tabelas financeiras existentes.
*/

CREATE TABLE EVENTO_NOTIFICACAO_OUTBOX (
    ID_EVENTO INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CHAVE_IDEMPOTENCIA VARCHAR(160) NOT NULL,
    CATEGORIA VARCHAR(24) NOT NULL,
    ID_CONTA INTEGER,
    ID_USUARIO_DESTINO INTEGER,
    TIPO_REFERENCIA VARCHAR(32),
    ID_REFERENCIA INTEGER,
    DADOS_JSON VARCHAR(4000),
    PUBLICAR SMALLINT DEFAULT 1 NOT NULL,
    TENTATIVAS INTEGER DEFAULT 0 NOT NULL,
    PROXIMA_TENTATIVA TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    BLOQUEIO_TOKEN VARCHAR(36),
    BLOQUEIO_ATE TIMESTAMP,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    PUBLICADO_EM TIMESTAMP,
    ERRO_ULTIMO VARCHAR(500),
    CONSTRAINT PK_EV_NOTIF_OUTBOX PRIMARY KEY (ID_EVENTO),
    CONSTRAINT UQ_EV_NOTIF_IDEMP UNIQUE (CHAVE_IDEMPOTENCIA),
    CONSTRAINT FK_EV_NOTIF_CONTA FOREIGN KEY (ID_CONTA) REFERENCES CONTA (ID_CONTA),
    CONSTRAINT FK_EV_NOTIF_USUARIO FOREIGN KEY (ID_USUARIO_DESTINO) REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT CK_EV_NOTIF_CATEGORIA CHECK (CATEGORIA IN ('PIX', 'TRANSFERENCIA', 'BOLETO', 'CARTAO', 'INFORMATIVO', 'SEGURANCA_CRITICA')),
    CONSTRAINT CK_EV_NOTIF_PUBLICAR CHECK (PUBLICAR IN (0, 1))
);

CREATE INDEX IX_EV_NOTIF_PENDENTE ON EVENTO_NOTIFICACAO_OUTBOX (PUBLICAR, PUBLICADO_EM, PROXIMA_TENTATIVA, BLOQUEIO_ATE);

CREATE TABLE NOTIFICACAO (
    ID_NOTIFICACAO INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ID_EVENTO INTEGER NOT NULL,
    ID_CONTA INTEGER,
    ID_USUARIO_DESTINO INTEGER,
    CATEGORIA VARCHAR(24) NOT NULL,
    TITULO VARCHAR(160) NOT NULL,
    MENSAGEM VARCHAR(500) NOT NULL,
    DADOS_JSON VARCHAR(4000),
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_NOTIFICACAO PRIMARY KEY (ID_NOTIFICACAO),
    CONSTRAINT UQ_NOTIFICACAO_EVENTO UNIQUE (ID_EVENTO),
    CONSTRAINT FK_NOTIFICACAO_EVENTO FOREIGN KEY (ID_EVENTO) REFERENCES EVENTO_NOTIFICACAO_OUTBOX (ID_EVENTO),
    CONSTRAINT FK_NOTIFICACAO_CONTA FOREIGN KEY (ID_CONTA) REFERENCES CONTA (ID_CONTA),
    CONSTRAINT FK_NOTIFICACAO_USUARIO FOREIGN KEY (ID_USUARIO_DESTINO) REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT CK_NOTIFICACAO_CATEGORIA CHECK (CATEGORIA IN ('PIX', 'TRANSFERENCIA', 'BOLETO', 'CARTAO', 'INFORMATIVO', 'SEGURANCA_CRITICA'))
);

CREATE INDEX IX_NOTIFICACAO_CATEGORIA_DATA ON NOTIFICACAO (CATEGORIA, CRIADO_EM);

CREATE TABLE NOTIFICACAO_DESTINATARIO (
    ID_DESTINATARIO INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ID_NOTIFICACAO INTEGER NOT NULL,
    ID_USUARIO INTEGER NOT NULL,
    ID_CONTA INTEGER,
    LIDA_EM TIMESTAMP,
    SUPRIMIDA_EM TIMESTAMP,
    CONSTRAINT PK_NOTIF_DESTINATARIO PRIMARY KEY (ID_DESTINATARIO),
    CONSTRAINT UQ_NOTIF_DEST_USUARIO UNIQUE (ID_NOTIFICACAO, ID_USUARIO),
    CONSTRAINT FK_NOTIF_DEST_NOTIF FOREIGN KEY (ID_NOTIFICACAO) REFERENCES NOTIFICACAO (ID_NOTIFICACAO),
    CONSTRAINT FK_NOTIF_DEST_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT FK_NOTIF_DEST_CONTA FOREIGN KEY (ID_CONTA) REFERENCES CONTA (ID_CONTA)
);

CREATE INDEX IX_NOTIF_DEST_USUARIO_CONTA ON NOTIFICACAO_DESTINATARIO (ID_USUARIO, ID_CONTA);

CREATE TABLE PREFERENCIA_NOTIFICACAO (
    ID_USUARIO INTEGER NOT NULL,
    CATEGORIA VARCHAR(24) NOT NULL,
    ATIVO SMALLINT DEFAULT 1 NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_PREF_NOTIFICACAO PRIMARY KEY (ID_USUARIO, CATEGORIA),
    CONSTRAINT FK_PREF_NOTIF_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT CK_PREF_NOTIF_CATEGORIA CHECK (CATEGORIA IN ('PIX', 'TRANSFERENCIA', 'BOLETO', 'CARTAO', 'INFORMATIVO')),
    CONSTRAINT CK_PREF_NOTIF_ATIVO CHECK (ATIVO IN (0, 1))
);
