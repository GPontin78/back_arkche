CREATE OR ALTER TRIGGER TG_AI_USUARIO_LOG
FOR USUARIO
ACTIVE AFTER INSERT POSITION 32000
AS
DECLARE VARIABLE V_USUARIO VARCHAR(100);
DECLARE VARIABLE V_NOVO VARCHAR(2000);
BEGIN
    V_USUARIO = COALESCE(
        RDB$GET_CONTEXT('USER_SESSION', 'ARKHE_USUARIO_LOG'),
        RDB$GET_CONTEXT('USER_SESSION', 'ARKHE_ID_USUARIO'),
        CURRENT_USER
    );

    -- ID_USUARIO - TIPO - STATUS - TENTATIVAS - PRIMEIRO_ACESSO
    V_NOVO =
        COALESCE(CAST(NEW.ID_USUARIO AS VARCHAR(80)), '') || ' - ' ||
        COALESCE(CAST(NEW.TIPO AS VARCHAR(80)), '') || ' - ' ||
        COALESCE(CAST(NEW.STATUS AS VARCHAR(80)), '') || ' - ' ||
        COALESCE(CAST(NEW.TENTATIVAS AS VARCHAR(80)), '') || ' - ' ||
        COALESCE(CAST(NEW.PRIMEIRO_ACESSO AS VARCHAR(80)), '');

    EXECUTE STATEMENT
    (
        'INSERT INTO LOG
        (
            USUARIO,
            DATA_HORA,
            TABELA,
            ID_REGISTRO,
            ACAO,
            VALOR_ANTERIOR,
            VALOR_NOVO
        )
        VALUES (?, CURRENT_TIMESTAMP, ?, ?, ?, ?, ?)'
    )
    (
        :V_USUARIO,
        'USUARIO',
        NEW.ID_USUARIO,
        'INSERT',
        NULL,
        :V_NOVO
    )
    ON EXTERNAL DATA SOURCE '__LOG_DATA_SOURCE__'
    AS USER '__LOG_USUARIO__'
    PASSWORD '__LOG_SENHA__'
    WITH COMMON TRANSACTION;
END^

