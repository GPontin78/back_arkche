/*
   Limites individualizados e credito por cartao.
   Aplicar somente apos backup confirmado do banco principal.
   A politica em POLITICA_LIMITE_* continua sendo o teto do banco; os valores
   por conta apenas reduzem esse teto. O limite de credito permanece em CARTAO.
*/
SET BAIL ON;

CREATE TABLE LIMITE_CONTA_OPERACAO (
    ID_CONTA INTEGER NOT NULL,
    OPERACAO VARCHAR(20) NOT NULL,
    PERIODO VARCHAR(10) NOT NULL,
    LIMITE_POR_OPERACAO DECIMAL(18,2),
    LIMITE_POR_OPERACAO_FAVORITO DECIMAL(18,2),
    ATUALIZADO_POR INTEGER NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_LIM_CONTA_OPER PRIMARY KEY (ID_CONTA, OPERACAO, PERIODO),
    CONSTRAINT FK_LIM_CONTA_OPER_CONTA FOREIGN KEY (ID_CONTA) REFERENCES CONTA (ID_CONTA),
    CONSTRAINT FK_LIM_CONTA_OPER_USUARIO FOREIGN KEY (ATUALIZADO_POR) REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT CK_LIM_CONTA_OPER_OPER CHECK (OPERACAO IN ('TRANSFERENCIA', 'PAGAMENTO')),
    CONSTRAINT CK_LIM_CONTA_OPER_PER CHECK (PERIODO IN ('DIURNO', 'NOTURNO')),
    CONSTRAINT CK_LIM_CONTA_OPER_VAL CHECK (LIMITE_POR_OPERACAO IS NULL OR LIMITE_POR_OPERACAO > 0),
    CONSTRAINT CK_LIM_CONTA_OPER_FAV CHECK (LIMITE_POR_OPERACAO_FAVORITO IS NULL OR LIMITE_POR_OPERACAO_FAVORITO > 0)
);

CREATE TABLE LIMITE_CONTA_PERIODO (
    ID_CONTA INTEGER NOT NULL,
    PERIODO VARCHAR(10) NOT NULL,
    LIMITE_ACUMULADO DECIMAL(18,2),
    ATUALIZADO_POR INTEGER NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_LIM_CONTA_PER PRIMARY KEY (ID_CONTA, PERIODO),
    CONSTRAINT FK_LIM_CONTA_PER_CONTA FOREIGN KEY (ID_CONTA) REFERENCES CONTA (ID_CONTA),
    CONSTRAINT FK_LIM_CONTA_PER_USUARIO FOREIGN KEY (ATUALIZADO_POR) REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT CK_LIM_CONTA_PER_PER CHECK (PERIODO IN ('DIURNO', 'NOTURNO')),
    CONSTRAINT CK_LIM_CONTA_PER_VAL CHECK (LIMITE_ACUMULADO IS NULL OR LIMITE_ACUMULADO > 0)
);

CREATE TABLE AUDITORIA_LIMITE_CARTAO (
    ID_AUDITORIA INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ID_ADMINISTRADOR INTEGER NOT NULL,
    ID_CARTAO INTEGER NOT NULL,
    ID_CONTA INTEGER NOT NULL,
    LIMITE_ANTERIOR DECIMAL(15,2) NOT NULL,
    LIMITE_NOVO DECIMAL(15,2) NOT NULL,
    MOTIVO VARCHAR(250) NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_AUD_LIM_CARTAO PRIMARY KEY (ID_AUDITORIA),
    CONSTRAINT FK_AUD_LIM_CARTAO_ADMIN FOREIGN KEY (ID_ADMINISTRADOR) REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT FK_AUD_LIM_CARTAO_CARTAO FOREIGN KEY (ID_CARTAO) REFERENCES CARTAO (ID_CARTAO),
    CONSTRAINT FK_AUD_LIM_CARTAO_CONTA FOREIGN KEY (ID_CONTA) REFERENCES CONTA (ID_CONTA),
    CONSTRAINT CK_AUD_LIM_CARTAO_VAL CHECK (LIMITE_ANTERIOR >= 0 AND LIMITE_NOVO > 0)
);

CREATE INDEX IX_AUD_LIM_CARTAO_DATA ON AUDITORIA_LIMITE_CARTAO (CRIADO_EM);
CREATE INDEX IX_AUD_LIM_CARTAO_CONTA ON AUDITORIA_LIMITE_CARTAO (ID_CONTA, CRIADO_EM);

/* Mantem controle concorrente para contas que existiam antes da migracao. */
INSERT INTO CONTROLE_LIMITE_CONTA (ID_CONTA, VERSAO)
SELECT C.ID_CONTA, 0 FROM CONTA C
WHERE NOT EXISTS (SELECT 1 FROM CONTROLE_LIMITE_CONTA L WHERE L.ID_CONTA = C.ID_CONTA);

/* O vinculo elimina contabilizacao em dobro entre COMPRA e MOVIMENTACAO. */
ALTER TABLE MOVIMENTACAO ADD ID_COMPRA INTEGER;
ALTER TABLE MOVIMENTACAO ADD CONSTRAINT FK_MOV_COMPRA_LIMITE FOREIGN KEY (ID_COMPRA) REFERENCES COMPRA (ID_COMPRA);
CREATE INDEX IX_MOV_COMPRA_LIMITE ON MOVIMENTACAO (ID_COMPRA);

ALTER TABLE AUDITORIA_LIMITE DROP CONSTRAINT CK_AUD_LIM_EVENTO;
ALTER TABLE AUDITORIA_LIMITE ADD CONSTRAINT CK_AUD_LIM_EVENTO
    CHECK (EVENTO IN ('POLITICA_ATUALIZADA', 'OPERACAO_RECUSADA', 'LIMITE_CONTA_ATUALIZADO'));

COMMIT;
