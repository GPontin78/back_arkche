/* Propostas da IA; nenhuma alteração nas tabelas de LOG ou nos registros antigos. */
SET BAIL ON;

CREATE TABLE MAURO_CADASTRO_PROPOSTA (
    ID_PROPOSTA BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CONVERSA BIGINT NOT NULL REFERENCES MAURO_CONVERSA (ID_CONVERSA),
    ID_USUARIO INTEGER NOT NULL REFERENCES USUARIO (ID_USUARIO),
    ID_CONTA INTEGER NOT NULL REFERENCES CONTA (ID_CONTA),
    ACAO VARCHAR(30) NOT NULL,
    DADOS BLOB SUB_TYPE TEXT CHARACTER SET UTF8 NOT NULL,
    STATUS VARCHAR(14) DEFAULT 'COLETANDO' NOT NULL,
    ID_REGISTRO BIGINT,
    CRIADA_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    EXPIRA_EM TIMESTAMP NOT NULL,
    CONFIRMADA_EM TIMESTAMP,
    RESULTADO VARCHAR(500),
    CONSTRAINT CK_MAURO_CAD_STATUS CHECK (STATUS IN
        ('COLETANDO','PREPARADA','VERIFICANDO','EXECUTADA','CANCELADA','EXPIRADA','RECUSADA','ALTERADA')),
    CONSTRAINT CK_MAURO_CAD_ACAO CHECK (ACAO IN
        ('EDITAR_PERFIL','CADASTRAR_CHAVE','EXCLUIR_CHAVE',
         'CADASTRAR_FAVORITO','EDITAR_FAVORITO','EXCLUIR_FAVORITO'))
);

CREATE INDEX IX_MAURO_CAD_CONVERSA ON MAURO_CADASTRO_PROPOSTA
    (ID_CONVERSA, ID_USUARIO, ID_CONTA, ID_PROPOSTA);

CREATE TABLE MAURO_CADASTRO_PIN_TENTATIVA (
    ID_TENTATIVA BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PROPOSTA BIGINT NOT NULL REFERENCES MAURO_CADASTRO_PROPOSTA (ID_PROPOSTA),
    ID_USUARIO INTEGER NOT NULL REFERENCES USUARIO (ID_USUARIO),
    VALIDO SMALLINT NOT NULL CHECK (VALIDO IN (0,1)),
    CRIADA_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX IX_MAURO_CAD_PIN_USUARIO ON MAURO_CADASTRO_PIN_TENTATIVA
    (ID_USUARIO, VALIDO, CRIADA_EM);

CREATE TABLE MAURO_ADMIN_MENSAGEM (
    ID_MENSAGEM BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_USUARIO INTEGER NOT NULL REFERENCES USUARIO (ID_USUARIO),
    PAPEL VARCHAR(12) NOT NULL CHECK (PAPEL IN ('USUARIO','ASSISTENTE')),
    CONTEUDO VARCHAR(4000) NOT NULL,
    CRIADA_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX IX_MAURO_ADMIN_HIST ON MAURO_ADMIN_MENSAGEM (ID_USUARIO, ID_MENSAGEM);
COMMIT;
