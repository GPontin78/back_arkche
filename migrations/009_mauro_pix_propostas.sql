SET BAIL ON;

CREATE TABLE MAURO_PIX_PROPOSTA (
    ID_PROPOSTA BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ID_CONVERSA BIGINT NOT NULL,
    ID_USUARIO INTEGER NOT NULL,
    ID_CONTA_ORIGEM INTEGER NOT NULL,
    ID_CONTA_DESTINO INTEGER,
    TIPO_DESTINO VARCHAR(12),
    TIPO_CHAVE VARCHAR(12),
    CHAVE_HASH CHAR(64),
    VALOR DECIMAL(18,2),
    NOME_ORIGEM VARCHAR(160) NOT NULL,
    NOME_DESTINATARIO VARCHAR(160),
    CONTA_ORIGEM_RESUMO VARCHAR(80) NOT NULL,
    CONTA_DESTINO_RESUMO VARCHAR(80),
    STATUS VARCHAR(12) DEFAULT 'COLETANDO' NOT NULL,
    CRIADA_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    EXPIRA_EM TIMESTAMP NOT NULL,
    PREPARADA_EM TIMESTAMP,
    CONFIRMADA_EM TIMESTAMP,
    CANCELADA_EM TIMESTAMP,
    ID_MOVIMENTACAO BIGINT,
    MOTIVO_STATUS VARCHAR(500),
    CONSTRAINT PK_MAURO_PIX_PROP PRIMARY KEY (ID_PROPOSTA),
    CONSTRAINT FK_MAURO_PIX_PROP_CONV FOREIGN KEY (ID_CONVERSA) REFERENCES MAURO_CONVERSA (ID_CONVERSA),
    CONSTRAINT FK_MAURO_PIX_PROP_USER FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT FK_MAURO_PIX_PROP_ORIG FOREIGN KEY (ID_CONTA_ORIGEM) REFERENCES CONTA (ID_CONTA),
    CONSTRAINT FK_MAURO_PIX_PROP_DEST FOREIGN KEY (ID_CONTA_DESTINO) REFERENCES CONTA (ID_CONTA),
    CONSTRAINT CK_MAURO_PIX_PROP_STATUS CHECK (STATUS IN ('COLETANDO', 'PREPARADA', 'EXECUTADA', 'CANCELADA', 'EXPIRADA', 'RECUSADA', 'ALTERADA')),
    CONSTRAINT CK_MAURO_PIX_PROP_DEST CHECK (TIPO_DESTINO IS NULL OR TIPO_DESTINO IN ('CHAVE', 'CONTA')),
    CONSTRAINT CK_MAURO_PIX_PROP_VALOR CHECK (VALOR IS NULL OR VALOR > 0),
    CONSTRAINT CK_MAURO_PIX_PROP_CHAVE CHECK (TIPO_CHAVE IS NULL OR TIPO_CHAVE IN ('email', 'telefone', 'cpf', 'cnpj', 'aleatoria'))
);

CREATE INDEX IX_MAURO_PIX_PROP_CONV ON MAURO_PIX_PROPOSTA (ID_CONVERSA, ID_USUARIO, ID_CONTA_ORIGEM, ID_PROPOSTA);
CREATE INDEX IX_MAURO_PIX_PROP_STATUS ON MAURO_PIX_PROPOSTA (STATUS, EXPIRA_EM);

CREATE TABLE MAURO_PIX_PIN_TENTATIVA (
    ID_TENTATIVA BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ID_USUARIO INTEGER NOT NULL,
    ID_CONTA INTEGER NOT NULL,
    ID_PROPOSTA BIGINT NOT NULL,
    RESULTADO VARCHAR(12) NOT NULL,
    TENTATIVA_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_MAURO_PIX_PIN_TENT PRIMARY KEY (ID_TENTATIVA),
    CONSTRAINT FK_MAURO_PIX_PIN_USER FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT FK_MAURO_PIX_PIN_CONTA FOREIGN KEY (ID_CONTA) REFERENCES CONTA (ID_CONTA),
    CONSTRAINT FK_MAURO_PIX_PIN_PROP FOREIGN KEY (ID_PROPOSTA) REFERENCES MAURO_PIX_PROPOSTA (ID_PROPOSTA),
    CONSTRAINT CK_MAURO_PIX_PIN_RES CHECK (RESULTADO IN ('VALIDO', 'RECUSADO'))
);

CREATE INDEX IX_MAURO_PIX_PIN_USER ON MAURO_PIX_PIN_TENTATIVA (ID_USUARIO, RESULTADO, TENTATIVA_EM);
CREATE INDEX IX_MAURO_PIX_PIN_PROP ON MAURO_PIX_PIN_TENTATIVA (ID_PROPOSTA, TENTATIVA_EM);

COMMIT;
