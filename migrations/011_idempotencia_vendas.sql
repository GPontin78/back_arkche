/* Idempotencia duravel para vendas de cartao (API, maquininha e legado).
   A linha e inserida na mesma transacao de COMPRA e MOVIMENTACAO.
   Aplicar somente depois de backup validado do Firebird principal. */
SET BAIL ON;

CREATE TABLE IDEMPOTENCIA_VENDA (
    CANAL VARCHAR(20) NOT NULL,
    ESCOPO_ID VARCHAR(80) NOT NULL,
    CHAVE VARCHAR(128) NOT NULL,
    ASSINATURA CHAR(64) NOT NULL,
    ID_COMPRA INTEGER NOT NULL,
    ID_MOVIMENTACAO INTEGER,
    RESPOSTA_JSON VARCHAR(4000) NOT NULL,
    HTTP_STATUS SMALLINT DEFAULT 201 NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_IDEMPOTENCIA_VENDA PRIMARY KEY (CANAL, ESCOPO_ID, CHAVE),
    CONSTRAINT FK_IDEMP_VENDA_COMPRA FOREIGN KEY (ID_COMPRA) REFERENCES COMPRA (ID_COMPRA),
    CONSTRAINT FK_IDEMP_VENDA_MOV FOREIGN KEY (ID_MOVIMENTACAO) REFERENCES MOVIMENTACAO (ID_MOVIMENTACAO),
    CONSTRAINT CK_IDEMP_VENDA_STATUS CHECK (HTTP_STATUS BETWEEN 200 AND 299)
);

CREATE INDEX IX_IDEMP_VENDA_COMPRA ON IDEMPOTENCIA_VENDA (ID_COMPRA);
CREATE INDEX IX_IDEMP_VENDA_DATA ON IDEMPOTENCIA_VENDA (CRIADO_EM);

COMMIT;
