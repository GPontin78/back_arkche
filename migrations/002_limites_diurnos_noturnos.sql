CREATE TABLE POLITICA_LIMITE_OPERACAO (
    TIPO_CONTA VARCHAR(2) NOT NULL,
    OPERACAO VARCHAR(20) NOT NULL,
    PERIODO VARCHAR(10) NOT NULL,
    ATIVO SMALLINT DEFAULT 0 NOT NULL,
    LIMITE_POR_OPERACAO DECIMAL(18,2),
    ATUALIZADO_POR INTEGER,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_POL_LIM_OP PRIMARY KEY (TIPO_CONTA, OPERACAO, PERIODO),
    CONSTRAINT FK_POL_LIM_OP_ADMIN FOREIGN KEY (ATUALIZADO_POR) REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT CK_POL_LIM_OP_TIPO CHECK (TIPO_CONTA IN ('PF', 'PJ')),
    CONSTRAINT CK_POL_LIM_OP_OPER CHECK (OPERACAO IN ('TRANSFERENCIA', 'PAGAMENTO')),
    CONSTRAINT CK_POL_LIM_OP_PER CHECK (PERIODO IN ('DIURNO', 'NOTURNO')),
    CONSTRAINT CK_POL_LIM_OP_ATIVO CHECK (ATIVO IN (0, 1)),
    CONSTRAINT CK_POL_LIM_OP_VALOR CHECK (LIMITE_POR_OPERACAO IS NULL OR LIMITE_POR_OPERACAO > 0)
);

CREATE TABLE POLITICA_LIMITE_PERIODO (
    TIPO_CONTA VARCHAR(2) NOT NULL,
    PERIODO VARCHAR(10) NOT NULL,
    ATIVO SMALLINT DEFAULT 0 NOT NULL,
    LIMITE_ACUMULADO DECIMAL(18,2),
    ATUALIZADO_POR INTEGER,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_POL_LIM_PER PRIMARY KEY (TIPO_CONTA, PERIODO),
    CONSTRAINT FK_POL_LIM_PER_ADMIN FOREIGN KEY (ATUALIZADO_POR) REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT CK_POL_LIM_PER_TIPO CHECK (TIPO_CONTA IN ('PF', 'PJ')),
    CONSTRAINT CK_POL_LIM_PER_PER CHECK (PERIODO IN ('DIURNO', 'NOTURNO')),
    CONSTRAINT CK_POL_LIM_PER_ATIVO CHECK (ATIVO IN (0, 1)),
    CONSTRAINT CK_POL_LIM_PER_VALOR CHECK (LIMITE_ACUMULADO IS NULL OR LIMITE_ACUMULADO > 0)
);

