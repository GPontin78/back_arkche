    CONSTRAINT PK_CTRL_LIM_CONTA PRIMARY KEY (ID_CONTA),
    CONSTRAINT FK_CTRL_LIM_CONTA FOREIGN KEY (ID_CONTA) REFERENCES CONTA (ID_CONTA)
);

