/* Agendamentos de transferencias Pix e pagamentos Pix/boleto.
   A operacao financeira e seu recibo idempotente sao gravados na mesma
   transacao Firebird pelo worker. Nenhuma tabela financeira e recriada. */

SET BAIL ON;

CREATE TABLE AGENDAMENTO_FINANCEIRO (
    ID_AGENDAMENTO INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ID_USUARIO INTEGER NOT NULL,
    ID_CONTA INTEGER NOT NULL,
    TIPO_OPERACAO VARCHAR(20) NOT NULL,
    ID_CONTA_DESTINO INTEGER,
    ID_COBRANCA INTEGER,
    TIPO_CHAVE VARCHAR(12),
    HASH_CHAVE CHAR(64),
    VALOR DECIMAL(18,2) NOT NULL,
    DATA_AGENDADA TIMESTAMP NOT NULL,
    STATUS VARCHAR(12) DEFAULT 'AGENDADO' NOT NULL,
    TENTATIVAS SMALLINT DEFAULT 0 NOT NULL,
    TENTAR_APOS TIMESTAMP,
    TOKEN_EXECUCAO VARCHAR(36),
    LEASE_ATE TIMESTAMP,
    MOTIVO_FALHA VARCHAR(500),
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    EXECUTADO_EM TIMESTAMP,
    CANCELADO_EM TIMESTAMP,
    CONSTRAINT PK_AGENDAMENTO_FIN PRIMARY KEY (ID_AGENDAMENTO),
    CONSTRAINT FK_AGEND_FIN_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT FK_AGEND_FIN_CONTA FOREIGN KEY (ID_CONTA) REFERENCES CONTA (ID_CONTA),
    CONSTRAINT FK_AGEND_FIN_DESTINO FOREIGN KEY (ID_CONTA_DESTINO) REFERENCES CONTA (ID_CONTA),
    CONSTRAINT FK_AGEND_FIN_COBRANCA FOREIGN KEY (ID_COBRANCA) REFERENCES COBRANCA (ID_COBRANCA),
    CONSTRAINT CK_AGEND_FIN_TIPO CHECK (TIPO_OPERACAO IN ('TRANSFERENCIA', 'PIX_COBRANCA', 'BOLETO')),
    CONSTRAINT CK_AGEND_FIN_STATUS CHECK (STATUS IN ('AGENDADO', 'EXECUTANDO', 'CONCLUIDO', 'CANCELADO', 'FALHOU')),
    CONSTRAINT CK_AGEND_FIN_VALOR CHECK (VALOR > 0),
    CONSTRAINT CK_AGEND_FIN_ALVO CHECK (
        (TIPO_OPERACAO = 'TRANSFERENCIA' AND ID_CONTA_DESTINO IS NOT NULL AND ID_COBRANCA IS NULL AND TIPO_CHAVE IS NOT NULL AND HASH_CHAVE IS NOT NULL)
        OR
        (TIPO_OPERACAO IN ('PIX_COBRANCA', 'BOLETO') AND ID_CONTA_DESTINO IS NULL AND ID_COBRANCA IS NOT NULL AND TIPO_CHAVE IS NULL AND HASH_CHAVE IS NULL)
    )
);

CREATE INDEX IX_AGEND_FIN_PENDENTE
    ON AGENDAMENTO_FINANCEIRO (STATUS, DATA_AGENDADA, TENTAR_APOS, LEASE_ATE);
CREATE INDEX IX_AGEND_FIN_USUARIO_CONTA
    ON AGENDAMENTO_FINANCEIRO (ID_USUARIO, ID_CONTA, DATA_AGENDADA);

CREATE TABLE AGENDAMENTO_EXECUCAO (
    ID_AGENDAMENTO INTEGER NOT NULL,
    ID_MOVIMENTACAO INTEGER NOT NULL,
    EXECUTADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_AGENDAMENTO_EXECUCAO PRIMARY KEY (ID_AGENDAMENTO),
    CONSTRAINT UQ_AGENDAMENTO_EXEC_MOV UNIQUE (ID_MOVIMENTACAO),
    CONSTRAINT FK_AGEND_EXEC_AGEND FOREIGN KEY (ID_AGENDAMENTO) REFERENCES AGENDAMENTO_FINANCEIRO (ID_AGENDAMENTO),
    CONSTRAINT FK_AGEND_EXEC_MOV FOREIGN KEY (ID_MOVIMENTACAO) REFERENCES MOVIMENTACAO (ID_MOVIMENTACAO)
);

COMMIT;
