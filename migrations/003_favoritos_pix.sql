/* Favoritos Pix por usuário e conta ativa, com política específica opcional. */

SET BAIL ON;

ALTER TABLE POLITICA_LIMITE_OPERACAO
    ADD LIMITE_POR_OPERACAO_FAVORITO DECIMAL(18,2);

CREATE TABLE FAVORITO_PIX (
    ID_FAVORITO INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ID_CONTA INTEGER NOT NULL,
    ID_USUARIO INTEGER NOT NULL,
    ID_CONTA_DESTINO INTEGER NOT NULL,
    TIPO_CHAVE VARCHAR(12) NOT NULL,
    CHAVE_PIX VARCHAR(160) NOT NULL,
    CHAVE_HASH CHAR(64) NOT NULL,
    ROTULO VARCHAR(100) NOT NULL,
    NOME_DESTINATARIO VARCHAR(160) NOT NULL,
    ATIVO SMALLINT DEFAULT 1 NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_FAVORITO_PIX PRIMARY KEY (ID_FAVORITO),
    CONSTRAINT FK_FAV_PIX_ORIGEM FOREIGN KEY (ID_CONTA) REFERENCES CONTA (ID_CONTA),
    CONSTRAINT FK_FAV_PIX_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT FK_FAV_PIX_DESTINO FOREIGN KEY (ID_CONTA_DESTINO) REFERENCES CONTA (ID_CONTA),
    CONSTRAINT UQ_FAV_PIX_ESCOPO UNIQUE (ID_CONTA, ID_USUARIO, TIPO_CHAVE, CHAVE_HASH),
    CONSTRAINT CK_FAV_PIX_TIPO CHECK (TIPO_CHAVE IN ('email', 'telefone', 'cpf', 'cnpj', 'aleatoria')),
    CONSTRAINT CK_FAV_PIX_ATIVO CHECK (ATIVO IN (0, 1))
);

CREATE INDEX IX_FAVORITO_PIX_ESCOPO
    ON FAVORITO_PIX (ID_CONTA, ID_USUARIO, ATIVO);

CREATE INDEX IX_FAVORITO_PIX_DESTINO
    ON FAVORITO_PIX (ID_CONTA, ID_USUARIO, ID_CONTA_DESTINO, ATIVO);
