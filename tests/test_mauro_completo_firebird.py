    @classmethod
    def conectar(cls, banco=None):
        return fdb.connect(host=cls.host, port=cls.porta, database=str(banco or cls.principal),
                           user='SYSDBA', password=cls.senha, charset='UTF8')

    @classmethod
    def tearDownClass(cls):
        for caminho in (cls.principal, cls.arquivo):
            assert caminho.parent == cls.pasta and caminho.name.startswith(('mauro-teste-', 'mauro-log-teste-'))
            conexao = cls.conectar(caminho)
            conexao.drop_database()
        if cls.pasta_local:
            cls.pasta.rmdir()

    def sql(self, sql, parametros=(), banco=None):
        conexao = self.conectar(banco)
        cursor = conexao.cursor()
        try:
            cursor.execute(sql, parametros)
            linhas = cursor.fetchall() if cursor.description else []
            conexao.commit()
            return linhas
        finally:
            cursor.close()
            conexao.close()

