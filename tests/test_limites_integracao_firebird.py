    def test_compra_e_movimentacao_contam_uma_vez_incluindo_fluxo_legado(self):
        agora = self.now
        self.sql('''INSERT INTO COMPRA (ID_CARTAO, VALOR_COMPRA, DATA_COMPRA, TIPO, VALOR_PARCELA, QTD_PARCELA)
                    VALUES (501, 100, ?, 1, 100, 1)''', (agora,))
        self.sql('''INSERT INTO MOVIMENTACAO (ID_PAGADOR, ID_RECEBEDOR, VALOR, DATA_MOVIMENTACAO)
                    VALUES (1, 1, 95, ?)''', (agora,))  # espelha o débito próprio legado em compra.py
