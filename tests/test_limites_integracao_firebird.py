    @classmethod
    def _criar_esquema_base(cls):
        cursor = cls.database.cursor()
        comandos = [
            '''CREATE TABLE USUARIO (
                 ID_USUARIO INTEGER NOT NULL PRIMARY KEY, NOME VARCHAR(100), EMAIL VARCHAR(150),
                 TELEFONE VARCHAR(30), CPF VARCHAR(20), CNPJ VARCHAR(20), TIPO INTEGER, STATUS INTEGER)''',
            '''CREATE TABLE CONTA (
                 ID_CONTA INTEGER NOT NULL PRIMARY KEY, ID_USUARIO INTEGER NOT NULL REFERENCES USUARIO,
                 TIPO_CONTA INTEGER NOT NULL, NUMERO_CONTA VARCHAR(20), AGENCIA VARCHAR(10), BANCO VARCHAR(40),
                 CNPJ VARCHAR(20), NOME_FANTASIA VARCHAR(100), RAZAO_SOCIAL VARCHAR(100))''',
            '''CREATE TABLE ACESSO_CONTA (
                 ID_CONTA INTEGER NOT NULL REFERENCES CONTA, ID_USUARIO INTEGER NOT NULL REFERENCES USUARIO,
                 STATUS INTEGER NOT NULL, CARGO VARCHAR(40), PRIMARY KEY (ID_CONTA, ID_USUARIO))''',
            '''CREATE TABLE CARTAO (
                 ID_CARTAO INTEGER NOT NULL PRIMARY KEY, ID_CONTA INTEGER NOT NULL REFERENCES CONTA,
                 NUMERO_CARTAO VARCHAR(19) NOT NULL, LIMITE DECIMAL(15,2), STATUS INTEGER DEFAULT 0 NOT NULL)''',
            '''CREATE TABLE COMPRA (
                 ID_COMPRA INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                 ID_CARTAO INTEGER NOT NULL REFERENCES CARTAO, VALOR_COMPRA DECIMAL(15,2) NOT NULL,
                 DATA_COMPRA TIMESTAMP NOT NULL, TIPO INTEGER NOT NULL,
                 VALOR_PARCELA DECIMAL(15,2), QTD_PARCELA INTEGER)''',
            '''CREATE TABLE FATURA_COMPRA (
                 ID_FATURA_COMPRA INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                 ID_COMPRA INTEGER NOT NULL REFERENCES COMPRA, STATUS INTEGER NOT NULL,
                 VALOR_PARCELA DECIMAL(15,2) NOT NULL)''',
            '''CREATE TABLE MOVIMENTACAO (
                 ID_MOVIMENTACAO INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                 ID_PAGADOR INTEGER NOT NULL REFERENCES CONTA, ID_RECEBEDOR INTEGER REFERENCES CONTA,
                 VALOR DECIMAL(15,2) NOT NULL, DATA_MOVIMENTACAO TIMESTAMP NOT NULL,
                 ID_COBRANCA INTEGER)''',
        ]
        for comando in comandos:
            cursor.execute(comando)
            cls.database.commit()
        cursor.close()

    @classmethod
    def _aplicar_migracao(cls, caminho):
        resultado = subprocess.run(
            [str(ISQL), '-user', 'SYSDBA', '-password', cls.password,
             '-i', str(caminho), f'localhost:{cls.db_path}'],
            capture_output=True, text=True, timeout=60,
        )
        if resultado.returncode:
            raise AssertionError(
                f'Migracao isolada falhou: {caminho.name}\n{resultado.stdout}\n{resultado.stderr}'
            )

