    def test_concorrencia_nao_ultrapassa_limite_acumulado_da_mesma_conta(self):
        self.sql("UPDATE POLITICA_LIMITE_PERIODO SET LIMITE_ACUMULADO = 100 WHERE TIPO_CONTA = 'PF' AND PERIODO = 'DIURNO'")
        barreira = threading.Barrier(2)

        def operar(_):
            with self.app.app_context(), self.app.test_request_context('/teste/concorrencia', method='POST'):
                cursor = banco.con.cursor()
                barreira.wait(timeout=10)
                resultado = self.service.aplicar_limite(cursor, 3, 'TRANSFERENCIA', Decimal('60'), id_usuario=12)
                if resultado is None:
                    cursor.execute('''INSERT INTO MOVIMENTACAO (ID_PAGADOR, ID_RECEBEDOR, VALOR, DATA_MOVIMENTACAO)
                                      VALUES (3, 2, 60, ?)''', (self.now,))
                    time.sleep(0.15)
                    banco.con.commit()
                    retorno = 200
                else:
                    retorno = resultado[1]
                cursor.close()
                return retorno

        from concurrent.futures import ThreadPoolExecutor
        with ThreadPoolExecutor(max_workers=2) as pool:
            resultados = list(pool.map(operar, range(2)))
        self.assertEqual(resultados.count(200), 1, resultados)
        self.assertEqual(resultados.count(403), 1, resultados)
        movimentacoes = self.sql('SELECT VALOR FROM MOVIMENTACAO WHERE ID_PAGADOR = 3')
        self.assertEqual(sum((Decimal(str(row[0])) for row in movimentacoes), Decimal('0.00')), Decimal('60.00'))


