    @classmethod
    def tearDownClass(cls):
        cls.con.close()
        cls.audit.close()
        # Apenas bancos criados por esta classe, na pasta temporária própria.
        for nome in (cls.principal, cls.arquivo):
            if not nome.name.startswith('arkhe-log-teste-'):
                raise RuntimeError('Cleanup recusado: banco fora do nome temporário de teste')
            c = fdb.connect(host=HOST, port=PORT, database=str(nome), user='SYSDBA', password=cls.senha)
            c.drop_database()
        if cls.pasta_local:
            cls.pasta.rmdir()

    def sql(self, sql, params=(), banco=None):
        c = (banco or self.con).cursor()
        try:
            c.execute(sql, params)
            return c.fetchall() if c.description else []
        finally:
            c.close()

    def eventos(self, tabela, registro):
        self.audit.rollback()
        return self.sql('''SELECT OPERACAO, DADOS_ANTERIORES, DADOS_NOVOS, ID_USUARIO, ID_CONTA
            FROM AUDITORIA_EVENTO WHERE TABELA_ORIGEM = ? AND ID_REGISTRO IS NOT DISTINCT FROM ? ORDER BY ID_AUDITORIA''',
            (tabela, registro), self.audit)

