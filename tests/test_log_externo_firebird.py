    @classmethod
    def _aplicar(cls, banco, caminho):
        from scripts.aplicar_log_externo import comandos_sql
        conexao = cls.audit if banco == cls.arquivo else cls.con
        for comando in comandos_sql(caminho.read_text(encoding='utf-8')):
            conexao.execute_immediate(comando)
        conexao.commit()

    @classmethod
    def _criar_schema(cls):
        tipos = {7: 'SMALLINT', 8: 'INTEGER', 10: 'FLOAT', 12: 'DATE', 13: 'TIME',
                 16: 'BIGINT', 27: 'DOUBLE PRECISION', 35: 'TIMESTAMP', 23: 'BOOLEAN'}
        for tabela in sorted({r[0] for r in cls.schema['fields']}):
            colunas = []
            for i, row in enumerate(r for r in cls.schema['fields'] if r[0] == tabela):
                _, nome, tipo, subtipo, tamanho, escala, padrao, obrigatorio = row
                if tipo in (14, 37):
                    sqltipo = f"{'CHAR' if tipo == 14 else 'VARCHAR'}({tamanho}) CHARACTER SET NONE"
                elif tipo == 261:
                    sqltipo = 'BLOB SUB_TYPE TEXT'
                elif subtipo in (1, 2) and tipo in (7, 8, 16):
                    sqltipo = f"{'NUMERIC' if subtipo == 1 else 'DECIMAL'}(18, {-escala})"
                else:
                    sqltipo = tipos[tipo]
                identidade = i == 0 and nome.startswith('ID_') and tipo in (8, 16)
                coluna = f'{nome} {sqltipo}'
                if identidade:
                    coluna += ' GENERATED BY DEFAULT AS IDENTITY'
                elif padrao:
                    coluna += ' ' + padrao
                if obrigatorio:
                    coluna += ' NOT NULL'
                colunas.append(coluna)
            cls.con.execute_immediate(f'CREATE TABLE {tabela} (' + ','.join(colunas) + ')')
            cls.con.commit()

    @classmethod
    def _legado(cls):
        migration = (ROOT / 'migrations/007_auditoria_outbox_triggers.sql').read_text(encoding='utf-8')
        procedure = migration.split('CREATE OR ALTER PROCEDURE ', 1)[1].split('END^', 1)[0]
        cls.con.execute_immediate('CREATE OR ALTER PROCEDURE ' + procedure + 'END')
        cls.con.commit()
        for nome, tabela, tipo, posicao, inativo, corpo in cls.schema['triggers']:
            evento = {2: 'INSERT', 4: 'UPDATE', 6: 'DELETE'}[tipo]
            cls.con.execute_immediate(f'CREATE TRIGGER {nome} FOR {tabela} ACTIVE AFTER {evento} POSITION {posicao} {corpo}')
        cls.con.commit()
        # Histórico que deve sobreviver à troca das triggers.
        cls.audit.cursor().execute("INSERT INTO AUDITORIA_EVENTO (ORIGEM_ID, ID_EVENTO_ORIGEM, EVENTO, TABELA_ORIGEM, OPERACAO, RESULTADO, CRIADO_EM) VALUES ('legado', 1, 'HISTORICO', 'FLASK', 'READ', 'SUCESSO', CURRENT_TIMESTAMP)")
        cls.audit.commit()

